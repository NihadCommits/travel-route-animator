// Writes src/overlays/flagUrls.ts: one import per country flag of flag-icons, so Vite and
// Remotion's webpack bundle each flag as a file of its own and load only the ones shown.
// Run again after updating flag-icons: pnpm --filter @travel-route-animator/scene flags
import { readdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const flagsDir = join(
  dirname(createRequire(import.meta.url).resolve('flag-icons/package.json')),
  'flags',
  '4x3',
);
// Two letters only: flag-icons also has regions such as gb-sct, which no border here names.
const codes = readdirSync(flagsDir)
  .map((file) => /^([a-z]{2})\.svg$/.exec(file)?.[1])
  .filter((code): code is string => code !== undefined)
  .sort();

const lines = [
  '// Generated by scripts/flag-urls.ts from flag-icons (MIT, github.com/lipis/flag-icons):',
  '// every country flag in 4:3 as a bundled file, so the flag block needs no download.',
  ...codes.map((code) => `import flag_${code} from 'flag-icons/flags/4x3/${code}.svg';`),
  '',
  '/** The URL of a country flag by lower-case ISO code. */',
  'export const FLAG_URLS: Readonly<Record<string, string>> = {',
  // Remotion declares *.svg imports as any (they may be components); here they are URLs.
  ...codes.map((code) => `  ${code}: flag_${code} as string,`),
  '};',
  '',
];
writeFileSync(join(here, '..', 'src', 'overlays', 'flagUrls.ts'), lines.join('\n'));
console.log(`${codes.length} flags`);
